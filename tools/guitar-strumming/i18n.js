  shared.registerCatalogs(catalogs);

  function translate(key, parameters = {}) {
    return shared.translate(key, parameters);
  }

  function formatValidationError(error) {
    const parameters = { ...(error.parameters || {}) };
    const key = `guitar.validation.${error.code}`;
    const translatedMessage = translate(key, parameters);
    const message = translatedMessage === key ? error.message : translatedMessage;
    const locations = [];
    if (error.section) locations.push(translate(`guitar.validation.section.${error.section}`));
    if (error.bar !== null) locations.push(translate('guitar.validation.bar', { bar: error.bar }));
    if (error.slot !== null) locations.push(translate('guitar.validation.slot', { slot: error.slot }));
    const line = error.line === null
      ? translate('guitar.validation.source')
      : translate('guitar.validation.line', { line: error.line });
    if (locations.length === 0) {
      return translate('guitar.validation.withoutLocation', { line, message });
    }
    const separator = shared.getLanguage() === 'zh-Hans' ? '、' : ', ';
    return translate('guitar.validation.withLocation', {
      line,
      location: locations.join(separator),
      message,
    });
  }

  return Object.freeze({ catalogs, formatValidationError, translate });
